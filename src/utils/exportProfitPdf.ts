import { jsPDF } from "jspdf";
import "./pdfSafeText"; // printable PDF text (₱, ≤, Ω ...)
import { pdfFitText, pdfWrapText } from "./pdfLayout";

export interface ProfitPdfTransaction {
  type: string; // 'revenue' | 'expense'
  title: string;
  category: string;
  amount: number;
  date: string;
}

export interface ProfitPdfData {
  dateFilter: string;
  activeRangeStats: { revenue: number; expenses: number; netProfit: number; profitMargin: number };
  statsOverview: {
    lifetimeRevenue: number;
    lifetimeExpenses: number;
    lifetimeNetProfit: number;
    lifetimeProfitMargin: number;
    profitToday: number;
    profitWeek: number;
    profitMonth: number;
    profitYear: number;
  };
  mergedTransactions: ProfitPdfTransaction[];
}

/** Administrator profit analytics report (A4 portrait). Amounts are right-aligned to their column edge. */
export function exportProfitReportPdf(data: ProfitPdfData): void {
  const { dateFilter, activeRangeStats, statsOverview, mergedTransactions } = data;
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4'
  });

  const fFormat = (val: number) => {
    return "PHP " + Number(val || 0).toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 });
  };

  // Style Swatches
  const PRIMARY_COLOR = [15, 23, 42];
  const ACCENT_COLOR = [245, 158, 11];
  const TEXT_MUTED = [100, 116, 139];
  const BG_LIGHT = [248, 250, 252];

  // Header Background
  doc.setFillColor(BG_LIGHT[0], BG_LIGHT[1], BG_LIGHT[2]);
  doc.rect(0, 0, 210, 38, 'F');

  // Accent line
  doc.setFillColor(ACCENT_COLOR[0], ACCENT_COLOR[1], ACCENT_COLOR[2]);
  doc.rect(15, 12, 1.5, 12, 'F');

  // Title Block
  doc.setFont("Helvetica", "bold");
  doc.setFontSize(22);
  doc.setTextColor(PRIMARY_COLOR[0], PRIMARY_COLOR[1], PRIMARY_COLOR[2]);
  doc.text("ELECTRICALPH", 20, 21);

  doc.setFont("Helvetica", "bold");
  doc.setFontSize(8);
  doc.setTextColor(TEXT_MUTED[0], TEXT_MUTED[1], TEXT_MUTED[2]);
  doc.text("ADMINISTRATOR FINANCIAL & PROFIT ANALYTICS REPORT", 20, 26);

  // Generation Info (Top Right)
  doc.setFont("Helvetica", "normal");
  doc.setFontSize(8);
  doc.setTextColor(TEXT_MUTED[0], TEXT_MUTED[1], TEXT_MUTED[2]);
  doc.text(`Export Date: ${new Date().toLocaleDateString('en-US')}`, 195, 18, { align: 'right' });
  pdfFitText(doc, `Active Filter: ${dateFilter.toUpperCase()}`, 195, 22, 60, { align: 'right' });
  doc.text(`Generated By: Platform Administrator`, 195, 26, { align: 'right' });

  // Financial Metrics Section: two cards, labels left and values right-aligned inside each card
  doc.setFillColor(BG_LIGHT[0], BG_LIGHT[1], BG_LIGHT[2]);
  doc.rect(15, 45, 180, 40, 'F');

  const metricRows = (x: number, valueRight: number, title: string, rows: Array<[string, string, boolean]>) => {
    doc.setFont("Helvetica", "bold");
    doc.setFontSize(10);
    doc.setTextColor(PRIMARY_COLOR[0], PRIMARY_COLOR[1], PRIMARY_COLOR[2]);
    doc.text(title, x, 52);
    doc.setFontSize(9);
    rows.forEach(([label, value, bold], i) => {
      const ry = 60 + i * 6;
      doc.setFont("Helvetica", bold ? "bold" : "normal");
      doc.text(label, x, ry);
      const labelW = doc.getTextWidth(label);
      pdfFitText(doc, value, valueRight, ry, valueRight - x - labelW - 3, { align: 'right', minFontSize: 6.5 });
    });
  };

  metricRows(20, 102, "FINANCIAL SUMMARY & MARGINS", [
    ["Total Gross Revenue:", fFormat(activeRangeStats.revenue), false],
    ["Total Operating Expenses:", fFormat(activeRangeStats.expenses), false],
    ["Net Operating Profit:", fFormat(activeRangeStats.netProfit), true],
    ["Net Profit Margin:", `${activeRangeStats.profitMargin.toFixed(2)} %`, true],
  ]);
  metricRows(112, 190, "LIFETIME METRICS", [
    ["Gross Revenue:", fFormat(statsOverview.lifetimeRevenue), false],
    ["Total Expenses:", fFormat(statsOverview.lifetimeExpenses), false],
    ["Net Profit:", fFormat(statsOverview.lifetimeNetProfit), true],
    ["Margin:", `${statsOverview.lifetimeProfitMargin.toFixed(2)} %`, true],
  ]);

  // Historical Period profit breakdowns
  doc.setFont("Helvetica", "bold");
  doc.setFontSize(10);
  doc.setTextColor(PRIMARY_COLOR[0], PRIMARY_COLOR[1], PRIMARY_COLOR[2]);
  doc.text("PERIODIC PROFIT INSIGHTS", 15, 96);

  doc.setFont("Helvetica", "normal");
  doc.setFontSize(8.5);
  const periodic: Array<[string, number, number, number]> = [
    ["Daily Profit (Today):", statsOverview.profitToday, 15, 102],
    ["Weekly Profit (This Week):", statsOverview.profitWeek, 15, 102],
    ["Monthly Profit (This Month):", statsOverview.profitMonth, 110, 195],
    ["Yearly Profit (This Year):", statsOverview.profitYear, 110, 195],
  ];
  periodic.forEach(([label, value, x, right], i) => {
    const py = 104 + (i % 2) * 6;
    doc.text(label, x, py);
    pdfFitText(doc, fFormat(value), right, py, right - x - doc.getTextWidth(label) - 3, { align: 'right', minFontSize: 6.5 });
  });

  // Line separator
  doc.setDrawColor(226, 232, 240);
  doc.line(15, 116, 195, 116);

  // Merged Transactions Ledger
  doc.setFont("Helvetica", "bold");
  doc.setFontSize(10);
  doc.text("CHRONOLOGICAL LEDGER (REVENUE & EXPENSES)", 15, 124);

  // Columns: [x, width]; AMOUNT is right-aligned to the table edge
  const col = { date: [18, 20], title: [40, 58], category: [100, 42], type: [144, 18], amountRight: 193 } as const;
  let y = 130;
  doc.setFillColor(15, 23, 42);
  doc.rect(15, y, 180, 6, 'F');
  doc.setFont("Helvetica", "bold");
  doc.setFontSize(7.5);
  doc.setTextColor(255, 255, 255);
  doc.text("DATE", col.date[0], y + 4.2);
  doc.text("TRANSACTION DETAILS", col.title[0], y + 4.2);
  doc.text("CATEGORY", col.category[0], y + 4.2);
  doc.text("TYPE", col.type[0], y + 4.2);
  doc.text("AMOUNT", col.amountRight, y + 4.2, { align: 'right' });

  doc.setFont("Helvetica", "normal");
  doc.setTextColor(PRIMARY_COLOR[0], PRIMARY_COLOR[1], PRIMARY_COLOR[2]);

  const txToShow = mergedTransactions.slice(0, 12);
  txToShow.forEach((tx, i) => {
    y += 7;

    // Alternating zebra rows
    if (i % 2 === 0) {
      doc.setFillColor(BG_LIGHT[0], BG_LIGHT[1], BG_LIGHT[2]);
      doc.rect(15, y, 180, 6.5, 'F');
    }

    const ty = y + 4.3;
    doc.setFont("Helvetica", "normal");
    doc.setTextColor(PRIMARY_COLOR[0], PRIMARY_COLOR[1], PRIMARY_COLOR[2]);
    pdfFitText(doc, tx.date.substring(0, 10), col.date[0], ty, col.date[1], { minFontSize: 6 });
    pdfFitText(doc, tx.title, col.title[0], ty, col.title[1], { minFontSize: 6.5 });
    pdfFitText(doc, tx.category, col.category[0], ty, col.category[1], { minFontSize: 6.5 });

    doc.setFont("Helvetica", "bold");
    if (tx.type === 'revenue') doc.setTextColor(16, 185, 129); // emerald Green
    else doc.setTextColor(239, 68, 68); // Red
    doc.text(tx.type === 'revenue' ? "INCOME" : "EXPENSE", col.type[0], ty);

    doc.setFont("Helvetica", "normal");
    doc.setTextColor(PRIMARY_COLOR[0], PRIMARY_COLOR[1], PRIMARY_COLOR[2]);
    pdfFitText(doc, fFormat(tx.amount), col.amountRight, ty, 29, { align: 'right', minFontSize: 6 });
  });

  if (mergedTransactions.length > 12) {
    doc.setFont("Helvetica", "normal");
    doc.setFontSize(7.5);
    doc.setTextColor(TEXT_MUTED[0], TEXT_MUTED[1], TEXT_MUTED[2]);
    pdfWrapText(doc, `* Showing first 12 records of ${mergedTransactions.length} total transactions in this period. See Excel sheets for full raw data logs.`, 15, y + 13, 180, 3.8);
  }

  doc.save(`Profit_Analytics_Report_${new Date().toISOString().substring(0,10)}.pdf`);
}
